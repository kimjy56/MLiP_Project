# -*- coding: utf-8 -*-
"""AS-06 noise robustness on fold-0 validation rows (fold-fit matcher; ko_map ON vs OFF).

NOTE: catalog_full_ko_map was generated by a model trained on ALL train rows, so the
'ko_map ON' Hangul numbers are leaky. 'ko_map OFF' isolates the legacy path.
"""
import json
import sys
import time
from copy import deepcopy
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "artifacts/AS-06"))
from script import CatalogIndex, fit_matching_model, is_korean_name, predict_rows  # noqa: E402
from eval_kit.robustness import PRESETS, RobustnessPerturber  # noqa: E402

SEED = 20261022
PRESET_NAMES = sys.argv[1].split(",") if len(sys.argv) > 1 else ["default", "severe"]


def metrics(preds, gold, ko):
    c = np.asarray(preds, dtype=object) == np.asarray(gold, dtype=object)
    ko = np.asarray(ko, dtype=bool)
    h = float(c[ko].mean()) if ko.any() else None
    n = float(c[~ko].mean()) if (~ko).any() else None
    return {"hangul": h, "hangul_rows": int(ko.sum()), "non_hangul": n,
            "non_hangul_rows": int((~ko).sum()),
            "weighted": 0.7 * h + 0.3 * n if h is not None and n is not None else None}


train = pd.read_csv(ROOT / "data/train.csv", dtype=str, keep_default_na=False, encoding="utf-8-sig")
catalog = pd.read_csv(ROOT / "data/vessel_catalog.csv", dtype=str, keep_default_na=False, encoding="utf-8-sig")
folds = pd.read_csv(ROOT / "eval_kit/folds_group5_seed42.csv", dtype={"sample_id": str, "fold": int}, encoding="utf-8-sig")
ko_map = json.loads((ROOT / "AR-06/catalog_full_ko_map.json").read_text(encoding="utf-8"))
merged = train.merge(folds[["sample_id", "fold"]], on="sample_id")
fit_df = merged[merged.fold != 0].reset_index(drop=True)
val_df = merged[merged.fold == 0].reset_index(drop=True)
model = fit_matching_model(fit_df, catalog, kr_mode="AR06", en_mode="EN_V3", use_train_lookup=False)
idx = {"ko_map_on": CatalogIndex(catalog, full_ko_map=ko_map),
       "ko_map_off": CatalogIndex(catalog, full_ko_map={})}
gold = val_df["target_vessel_id"].tolist()
ko = val_df["vessel_name"].apply(is_korean_name).values
report = {"fold": 0, "rows": len(val_df), "seed": SEED, "results": {}}
for pname in PRESET_NAMES:
    noisy, summ, _ = RobustnessPerturber(deepcopy(PRESETS[pname]), seed=SEED).perturb_dataset(
        val_df, catalog, return_row_audits=True)
    report["results"][pname] = {"noise_applied_rate": summ["any_noise_applied_rate"]}
    for iname, ci in idx.items():
        for dname, df in (("clean", val_df), ("noisy", noisy)):
            t0 = time.perf_counter()
            preds, _ = predict_rows(df, model, ci, use_train_lookup=False, gold_ids=gold)
            m = metrics(preds, gold, ko)
            m["seconds"] = time.perf_counter() - t0
            report["results"][pname][f"{iname}/{dname}"] = m
            print(pname, iname, dname, json.dumps(m, ensure_ascii=False), flush=True)
out = ROOT / "reports/robustness/robustness_AS-06_fold0.json"
out.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
print("saved", out)
